#   교과서에 없는 낱말로 응용한 문항은 해설에 "(교과서 밖 확장)"이라고 적는다.
#   spacing(띄어쓰기 50제)은 사용자가 준 PDF의 문항·정답을 그대로 옮긴 것이다.
# 문항 종류: B 빈칸 / OX / P 둘 중 고르기 / MC ①~⑤ / SP 띄어쓰기 고쳐 쓰기 / W 직접 쓰기 / E 서술형(모범 답 보고 스스로 채점)
