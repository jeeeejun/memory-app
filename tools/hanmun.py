def parse_tok(s):
    f = s.split("|") + [""] * 6
    c, e, m, col, note, tag = f[:6]
    assert col in TIER, s
    if m:
        assert len(e) == len(c), f"음 글자 수 != 한자 글자 수: {s}"
    return dict(c=c, e=e, m=m, col=col, note=note, tag=tag)


def best(cols):
    return min(cols, key=lambda c: RANK[c])


def blanks_ok(t):
    assert t.count("[") == t.count("]"), t
    return t


def plain(t):
    return re.sub(r"[\[\]]", "", t)


def main():
    unit_ids = [u[0] for u in UNITS]
    passages, items = [], []
    char_map = {}  # (c,e,m) -> item
    seen_ids = set()

    def add(it):
        assert it["id"] not in seen_ids, it["id"]
        seen_ids.add(it["id"])
        it["tier"] = TIER[it["col"]]
        items.append(it)

    for ps in PASSAGES:
        assert ps["unit"] in unit_ids, ps["unit"]
        if ps["id"] in HIDE:
            continue
        lines = []
        for i, ln in enumerate(ps["lines"]):
            toks = [parse_tok(s) for s in ln["toks"]]
            assert "".join(t["c"] for t in toks) == ln["h"], (ln["h"], "".join(t["c"] for t in toks))
            if ln["order"]:
                assert len(ln["order"]) == len(toks), ln["h"]
            blanks_ok(ln["t"])
            lid = f"{ps['id']}-{i + 1}"
            reading = "".join(t["e"] for t in toks)
            lines.append(dict(id=lid, h=ln["h"], r=reading, t=ln["t"], col=ln["col"],
                              label=ln["lid"] or "", order=ln["order"], toks=toks))
            # 낱자(뜻이 있는 것만) — 같은 (한자, 음, 뜻)은 하나로 합친다
            for t in toks:
                if not t["m"]:
                    continue
                key = (t["c"], t["e"], t["m"])
                ctx = dict(h=ln["h"], t=plain(ln["t"]), title=ps["title"], src=ps["id"])
                if key in char_map:
                    it = char_map[key]
                    it["cols"].append(t["col"])
                    if t["note"] and t["note"] not in it["notes"]:
                        it["notes"].append(t["note"])
                    if t["tag"] and t["tag"] not in it["tags"]:
                        it["tags"].append(t["tag"])
                    if ctx["h"] not in [x["h"] for x in it["ctx"]]:
                        it["ctx"].append(ctx)
                    it["units"] = sorted(set(it["units"] + [ps["unit"]]), key=unit_ids.index)
                else:
                    it = dict(kind="char", c=t["c"], e=t["e"], m=t["m"], cols=[t["col"]],
                              notes=[t["note"]] if t["note"] else [], tags=[t["tag"]] if t["tag"] else [],
                              ctx=[ctx], units=[ps["unit"]])
                    char_map[key] = it
            # 문장 해석·통째로 쓰기 (이야기·한시만; 성어·단문은 글 전체를 한 문항으로)
            if ps["kind"] in ("story", "poem"):
                add(dict(id=f"l:{lid}", kind="line", col=ln["col"], units=[ps["unit"]], src=ps["id"],
                         q=ln["h"], r=reading, a=ln["t"], label=ln["lid"] or "",
                         title=ps["title"], w=ln["h"], tags=[], exp=""))

        # 글 전체 / 성어 제목
        whole_h = "".join(l["h"] for l in lines)
        whole_r = " ".join(l["r"] for l in lines) if ps["kind"] == "idiom" else ps["reading"]
        if ps["kind"] == "idiom":
            assert ps["reading"].replace(" ", "") == whole_r.replace(" ", ""), (ps["reading"], whole_r)
            add(dict(id=f"i:{ps['id']}", kind="idiom", col=ps["col"], units=[ps["unit"]], src=ps["id"],
                     q=ps["title"], r=ps["reading"], a=ps["gist"], deep=ps["deep"], w=whole_h,
                     title=ps["title"], tags=[ps["tag"]] if ps.get("tag") else [], exp=""))
        elif ps["kind"] == "story":
            add(dict(id=f"i:{ps['id']}", kind="idiom", col=ps["col"], units=[ps["unit"]], src=ps["id"],
                     q=ps["title"], r=ps["reading"], a=ps["gist"], deep=ps["deep"], w=ps["title"],
                     title=ps["title"], tags=[ps["tag"]] if ps.get("tag") else [], exp=""))
        for j, (col, q, a, exp, tag) in enumerate(ps.get("points", [])):
            add(dict(id=f"p:{ps['id']}-{j + 1}", kind="point", col=col, units=[ps["unit"]], src=ps["id"],
                     q=q, a=a, exp=exp, w="", title=ps["title"], tags=[tag] if tag else []))

        passages.append(dict(id=ps["id"], unit=ps["unit"], kind=ps["kind"], title=ps["title"],
                             reading=ps["reading"], col=ps["col"], tag=ps.get("tag", ""),
                             gist=ps["gist"], deep=ps["deep"], note=ps.get("note", ""), src=ps["src"],
                             lines=lines, points=[f"p:{ps['id']}-{j + 1}" for j in range(len(ps.get("points", [])))]))

    for wid, h, r, m, why in WORDS:
        assert len(h) == len(r)
        blanks_ok(m)
        add(dict(id=f"w:{wid}", kind="word", col="P", units=["u11"], src="u11-w", q=h, r=r, a=m,
                 w=h, title="11단원 어휘 (보라 동그라미만)", tags=[], exp=why))
    passages.append(dict(id="u11-w", unit="u11", kind="words", title="어휘 (보라 동그라미만)", reading="",
                         col="P", tag="", gist="", deep="", note="빨간 글씨로만 채운 어휘 칸은 사용자 지시로 뺌.",
                         src="한문 11차시 학습지 p.1 어휘표 — 보라색 동그라미 낱말만", lines=[],
                         points=[f"w:{w[0]}" for w in WORDS]))

    # 낱자 항목 확정 (가장 높은 색)
    for (c, e, m), it in char_map.items():
        col = best(it.pop("cols"))
        add(dict(id=f"c:{c}:{e}:{m}", kind="char", col=col, units=it["units"], src=it["ctx"][0]["src"],
                 q=c, r=e, a=m, w=c, ctx=it["ctx"], notes=it["notes"], tags=it["tags"],
                 title=it["ctx"][0]["title"], exp=" / ".join(it["notes"])))

    # 단원 순서 → 글 순서 → 종류 순서로 정렬
    porder = {p["id"]: i for i, p in enumerate(passages)}
    korder = {"idiom": 0, "word": 1, "point": 2, "line": 3, "char": 4}
    items.sort(key=lambda x: (unit_ids.index(x["units"][0]), porder.get(x["src"], 999), korder[x["kind"]]))

    data = dict(
        subject="한문",
        source="한문 학습지 사진 (7·8·10·11·12차시) + 서술형 평가 대비(4~8단원) 인쇄물",
        rule="색 우선순위: 보라(1) → 빨강(2) → 파랑·검정(3)",
        exam="서술형(4~8단원): 성어 8문제, 단문 2문제 — 각 한자의 3요소(모양·음·뜻) 모두 알아야 함",
        units=[dict(id=u, title=t, sub=s) for u, t, s in UNITS],
        passages=passages, items=items)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    from collections import Counter
    print("글", len(passages), "· 문항", len(items))
    print("종류", dict(Counter(i["kind"] for i in items)))
    print("단계", dict(sorted(Counter(i["tier"] for i in items).items())))
    print("쓰기", sum(1 for i in items if i["w"]))


if __name__ == "__main__":
    main()
