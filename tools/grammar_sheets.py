d["sections"] = [s for s in d["sections"] if s["id"] != "art41"]
i = next(k for k, s in enumerate(d["sections"]) if s["id"] == "check")
d["sections"].insert(i, {"id": "art41", "title": "제41~43항 띄어쓰기"})
keep = [c for c in d["cards"] if c["section"] != "art41"]
new = [dict(id=f"kg-{100+k}", section="art41", front=fr, back=ba, **({"explain": ex} if ex else {})) for k, (fr, ba, ex) in enumerate(CARDS41, 1)]
j = next(k for k, c in enumerate(keep) if c["section"] == "check")
d["cards"] = keep[:j] + new + keep[j:]
for c in d["cards"]:
    if c["id"] == "kg-075": c["explain"] = "필기: 률 - 기본, 율 - 예외 / 짭짤: 비슷한 음절 → 된소리"
