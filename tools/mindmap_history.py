root = os.path.join(os.path.dirname(__file__), "..", "data")
cards = [c for c in json.load(open(os.path.join(root, "cards.json"), encoding="utf-8")) if c["subject"] == SUBJ and c.get("status") == "확정"]
units = {}
for c in cards: units.setdefault(c["unit"].split()[0], []).append(c.get("sentence") or "")
part_of = lambda code: code.rsplit("-", 1)[0] if "-" in code else code
for code in units: assert part_of(code) in PARTS, ("PARTS에 제목이 없는 큰 단원", code)

flows = {}
for code, spec in FLOW.items():
    assert code in units, ("카드에 없는 단원", code)
    sep, items = spec if isinstance(spec, tuple) else ("→", spec)
    out = []
    for it in items:
        show, find = it if isinstance(it, tuple) else (it, it)
        assert any(find in s for s in units[code]), ("단원 문장에 없는 말", code, find)
        out.append([show, find] if show != find else show)
    flows[code] = {"sep": sep, "items": out}

p = os.path.join(root, "mindmap.json")
data = json.load(open(p, encoding="utf-8")) if os.path.exists(p) else {}
data[SUBJ] = {"parts": PARTS, "flows": flows}
with open(p, "w", encoding="utf-8") as f:
    json.dump(data, f, ensure_ascii=False, indent=1); f.write("\n")
print(SUBJ, "마인드맵:", len(PARTS), "대단원,", len(flows), "/", len(units), "단원 흐름")
