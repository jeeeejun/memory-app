cards, sums, srcs = [], [], []
pages = {}
for ui, (unit, page, topics) in enumerate(U):
    code = unit.split()[0]
    pages[code] = (unit, page, ui)
    n = 0; body = []
    for topic, items in topics:
        body.append("## " + topic)
        for (s, blanks, q, a, exp) in items:
            for b in blanks: assert b in s, (b, s)
            n += 1
            cards.append({"id": f"kj-{code}-{n:02d}", "subject": SUBJ, "unit": unit, "topic": topic, "order": (BASE + ui + 1) * 1000 + n,
                          "lessonDate": DATE, "q": q, "a": a, "exp": exp, "sentence": s, "blanks": blanks,
                          "source": f"{page} ({MARK})", "status": "확정"})
            body.append("- " + s)
    sums.append({"id": f"kj-sum-{code}", "subject": SUBJ, "unit": unit, "lessonDate": DATE, "title": unit,
                 "body": "\n".join(body), "source": f"{page} ({MARK})"})
for i, (code, title, text, cite, ans, exp) in enumerate(S):
    unit, page, ui = pages[code]
    srcs.append({"id": f"kj-src-{i + 1:02d}", "subject": SUBJ, "unit": unit, "order": (BASE + ui + 1) * 1000 + i,
                 "lessonDate": DATE, "title": title, "text": text, "cite": cite, "a": ans, "exp": exp,
                 "source": f"{page} (사료)"})

root = os.path.join(os.path.dirname(__file__), "..", "data")
def merge(fname, new, prefix):
    p = os.path.join(root, fname)
    old = json.load(open(p, encoding="utf-8")) if os.path.exists(p) else []
    keep = [x for x in old if not x["id"].startswith(prefix)]
    out = keep + new
    with open(p, "w", encoding="utf-8") as f:
        f.write("[\n" + ",\n".join(json.dumps(x, ensure_ascii=False) for x in out) + "\n]\n")
merge("cards.json", cards, "kj-1")
merge("summaries.json", sums, "kj-sum-")
merge("sources.json", srcs, "kj-src-")
