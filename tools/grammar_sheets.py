import json, os, re

def B(q, a, exp="", rule=""): return dict(type="blank", q=q, answer=a, explain=exp, rule=rule)
def OX(q, a, exp="", rule=""): return dict(type="ox", q=q, answer=a, explain=exp, rule=rule)
def P(q, a, exp="", rule=""):
    m = re.search(r"\( (.+?) / (.+?) \)", q); assert m, q
    ch = [m.group(1), m.group(2)]; assert a in ch, (a, q)
    return dict(type="pick", q=q, choices=ch, answer=a, explain=exp, rule=rule)
def MC(q, ch, a, exp="", rule="", box=None):
    assert 1 <= a <= len(ch), q
    d = dict(type="mc", q=q, choices=ch, answer=a, explain=exp, rule=rule)
    if box: d["box"] = box
    return d
def SP(a, exp="", rule=""):
    return dict(type="space", q="띄어 써야 할 곳에 ∨ 표시를 하고, 아래에 바르게 고쳐 쓰시오.", text=a.replace(" ", ""), answer=a, explain=exp, rule=rule)
def W(q, a, exp="", rule=""): return dict(type="write", q=q, answer=a, explain=exp, rule=rule)
def E(q, a, exp="", rule="", lines=2): return dict(type="essay", q=q, answer=a, explain=exp, rule=rule, lines=lines)

