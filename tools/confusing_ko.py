def main():
    ids = {s[0] for s in SECTIONS}
    cards, cnt = [], {}
    for sec, f, b, e in CARDS:
        assert sec in ids, sec
        cnt[sec] = cnt.get(sec, 0) + 1
        cid = f"cf-{sec}-{cnt[sec]:02d}"
        if cid in HIDE:
            continue
        cards.append({"id": cid, "section": sec, "front": f, "back": b, "explain": e})
    data = {
        "deck": "헷갈리는 부분 — 국어 문법",
        "source": SOURCE,
        "sections": [{"id": i, "title": t, "summary": s} for i, t, s in SECTIONS],
        "cards": cards,
    }
    out = os.path.join(os.path.dirname(__file__), "..", "data", "confusing.json")
    with open(out, "w", encoding="utf-8") as fp:
        json.dump(data, fp, ensure_ascii=False, indent=1)
    print(f"sections {len(SECTIONS)}, cards {len(cards)} -> data/confusing.json")

if __name__ == "__main__":
    main()
